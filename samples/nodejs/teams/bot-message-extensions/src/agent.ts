import { Activity } from '@microsoft/agents-activity'
import { AgentApplication, MemoryStorage, RouteRank } from '@microsoft/agents-hosting'
import { TeamsAgentExtension } from '@microsoft/agents-hosting-extensions-msteams'
import { searchWikipedia, type Article } from './search.js'

function articleAttachment (article: Article) {
  let snippet = article.snippet ?? ''
  let previous: string
  do {
    previous = snippet
    snippet = snippet.replace(/<[^>]+>/g, '')
  } while (snippet !== previous)
  // Incomplete tags must not leave markup delimiters in card text.
  snippet = snippet.replace(/[<>]/g, '')
  const title = article.title || 'No Title'
  const url = `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replace(/ /g, '_'))}`
  return {
    contentType: 'application/vnd.microsoft.card.adaptive',
    content: {
      type: 'AdaptiveCard',
      version: '1.5',
      body: [
        { type: 'TextBlock', text: title, weight: 'Bolder', size: 'Large' },
        { type: 'TextBlock', text: snippet, wrap: true, isSubtle: true },
        { type: 'ActionSet', actions: [{ type: 'Action.OpenUrl', title: 'Read on Wikipedia', url }] },
      ],
    },
    preview: { contentType: 'application/vnd.microsoft.card.thumbnail', content: { title, text: snippet } },
  }
}

function noResults (query: string) {
  return { composeExtension: { type: 'message' as const, text: `No results found for '${query}'` } }
}

export function createAgent (services: { searchWikipedia?: typeof searchWikipedia } = {}) {
  const search = services.searchWikipedia ?? searchWikipedia
  const app = new AgentApplication({ storage: new MemoryStorage() })
  const teams = new TeamsAgentExtension(app)
  app.registerExtension(teams, (extension) => {
    extension.messageExtensions.onQuery('wikipediaSearch', async (_context, _state, query) => {
      const text = String(query.parameters?.[0]?.value ?? '')
      const articles = await search(text)
      if (articles.length === 0) {
        return noResults(text)
      }
      return {
        composeExtension: {
          type: 'result',
          attachmentLayout: 'list',
          attachments: articles.map(articleAttachment),
        }
      }
    })
    extension.messageExtensions.onQueryLink(async (_context, _state, query) => ({
      composeExtension: {
        type: 'result',
        attachmentLayout: 'list',
        attachments: [{
          contentType: 'application/vnd.microsoft.card.adaptive',
          content: {
            type: 'AdaptiveCard',
            version: '1.5',
            body: [
              { type: 'TextBlock', text: 'Link Preview', weight: 'Bolder', size: 'Medium' },
              { type: 'TextBlock', text: `URL: ${query?.url ?? ''}`, wrap: true },
              { type: 'TextBlock', text: 'This is a preview of the linked content generated by the message extension.', wrap: true },
            ],
          },
        }],
      },
    }))
  })
  // The generic upstream query route also answers unknown command IDs.
  app.addRoute(async (context) => context.activity.type === 'invoke' && context.activity.name === 'composeExtension/query', async (context) => {
    const value = context.activity.value as { parameters?: Array<{ value?: unknown }> } | undefined
    const query = String(value?.parameters?.[0]?.value ?? '')
    await context.sendActivity(Activity.fromObject({ type: 'invokeResponse', value: { status: 200, body: noResults(query) } }))
  }, true, RouteRank.Last)
  app.onActivity('message', async (context) => {
    if ((context.activity.text ?? '').toLowerCase().includes('help')) {
      await context.sendActivity("Hi! I'm the Search Messaging Extension Agent!\n\nUse me in the compose area to search for Wikipedia articles\n")
    } else {
      await context.sendActivity(`You said: ${context.activity.text}\n\nType 'help' to learn more.`)
    }
  })
  return app
}

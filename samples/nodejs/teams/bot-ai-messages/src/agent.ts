import { Activity, addAIToActivity } from '@microsoft/agents-activity'
import { AgentApplication, MemoryStorage, RouteRank } from '@microsoft/agents-hosting'
import { onTeamsFeedbackLoop, TeamsAgentExtension, teamsEnableFeedbackLoop } from '@microsoft/agents-hosting-extensions-msteams'

export function createAgent () {
  const app = new AgentApplication({ storage: new MemoryStorage() })
  const teams = new TeamsAgentExtension(app)
  app.registerExtension(teams, () => {
    onTeamsFeedbackLoop(app, async (context, _state, feedback) => {
      const reaction = feedback.actionValue?.reaction || 'No reaction'
      try {
        const raw = feedback.actionValue?.feedback
        const parsed = typeof raw === 'string' ? JSON.parse(raw) : raw
        const text = parsed?.feedbackText || 'No feedback was provided.'
        await context.sendActivity(`Provided reaction: ${reaction}<br> Feedback: ${text}`)
      } catch (error) {
        console.error('Invalid feedback payload:', error)
      }
    })
  })
  app.onMessage(/label/i, async (context) => {
    const message = Activity.fromObject({ type: 'message', text: 'Hi, this message is generated by AI' })
    addAIToActivity(message)
    await context.sendActivity(message)
  }, [], 10)
  app.onMessage(/sensitivity/i, async (context) => {
    await context.sendActivity(Activity.fromObject({
      type: 'message',
      text: 'This is an example of a sensitivity label that help users identify the confidentiality of a message',
      entities: [{
        type: 'https://schema.org/Message',
        '@type': 'Message',
        '@context': 'https://schema.org',
        '@id': '',
        usageInfo: {
          type: 'https://schema.org/Message',
          '@type': 'CreativeWork',
          description: 'Please be mindful of sharing outside of your team',
          name: 'Confidential \\ Contoso FTE',
        },
      }],
    }))
  }, [], 20)
  app.onMessage(/feedback/i, async (context) => {
    const message = Activity.fromObject({
      type: 'message', text: 'This is an example of a feedback button - this helps to provide feedback for a message',
    })
    teamsEnableFeedbackLoop(message)
    await context.sendActivity(message)
  }, [], 30)
  app.onMessage(/citation/i, async (context) => {
    const citation = {
      '@type': 'Claim',
      position: 1,
      appearance: {
        '@type': 'DigitalDocument',
        name: 'AI messages agent',
        url: 'https://example.com/claim-1',
        abstract: 'Excerpt description',
        text: JSON.stringify({ type: 'AdaptiveCard', version: '1.6', body: [{ type: 'TextBlock', text: 'Adaptive Card text' }] }),
        encodingFormat: 'application/vnd.microsoft.card.adaptive',
        keywords: ['keyword 1', 'keyword 2', 'keyword 3'],
        image: { '@type': 'ImageObject', name: 'Microsoft Word' },
      },
    }
    await context.sendActivity(Activity.fromObject({
      type: 'message',
      text: "Hey I'm a friendly AI agent. This message is generated through AI [1]",
      entities: [{
        type: 'https://schema.org/Message',
        '@type': 'Message',
        '@context': 'https://schema.org',
        '@id': '',
        citation: [citation],
      }],
    }))
  }, [], 40)
  app.onActivity('message', async (context) => {
    await context.sendActivity("Welcome to the AI agent! Try sending messages with keywords like 'label', 'sensitivity', 'feedback', or 'citation' to see different AI features.")
  }, [], RouteRank.Last)
  return app
}

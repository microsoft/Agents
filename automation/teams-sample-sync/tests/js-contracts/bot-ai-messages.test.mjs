import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { sampleHarness } from './harness.mjs'

describe('bot-ai-messages', () => {
  it('AI labels preserve route precedence over other keywords', async () => {
    const harness = await sampleHarness()
    const result = await harness.turn({ text: 'sensitivity label' })
    assert.equal(result.sent[0].text, 'Hi, this message is generated by AI')
    assert.ok(result.sent[0].entities[0].additionalType.includes('AIGeneratedContent'))
  })

  it('sensitivity and feedback commands retain their Teams metadata', async () => {
    const harness = await sampleHarness()
    const sensitivity = await harness.turn({ text: 'sensitivity' })
    assert.equal(sensitivity.sent[0].entities[0].usageInfo.name, 'Confidential \\ Contoso FTE')
    const feedback = await harness.turn({ text: 'feedback' })
    assert.equal(feedback.sent[0].channelData.feedbackLoop.type, 'default')
  })

  it('citation command includes the claim, source URL, keywords and card', async () => {
    const harness = await sampleHarness()
    const result = await harness.turn({ text: 'citation' })
    const claim = result.sent[0].entities[0].citation[0]
    assert.equal(claim.position, 1)
    assert.equal(claim.appearance.url, 'https://example.com/claim-1')
    assert.equal(claim.appearance.image.name, 'Microsoft Word')
    assert.equal(claim.appearance.encodingFormat, 'application/vnd.microsoft.card.adaptive')
    assert.equal(claim.appearance.keywords.length, 3)
    assert.equal(JSON.parse(claim.appearance.text).body[0].text, 'Adaptive Card text')
  })

  it('feedback invoke returns the reaction and feedback, while unknown messages return help', async () => {
    const harness = await sampleHarness()
    const result = await harness.turn({
      type: 'invoke',
      name: 'message/submitAction',
      value: {
        actionName: 'feedback',
        actionValue: {
          reaction: 'like',
          feedback: '{"feedbackText":"Useful"}'
        }
      },
    })
    assert.ok(result.sent.some((activity) => activity.text === 'Provided reaction: like<br> Feedback: Useful'))
    assert.equal(result.invoke.value.status, 200)
    const help = await harness.turn({ text: 'unknown' })
    assert.match(help.sent[0].text, /label.*sensitivity.*feedback.*citation/)
  })
})
